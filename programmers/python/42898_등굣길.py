def solution(m, n, puddles):
    '''
    [문제]
    - (1, 1)에서 (m, n)까지 오른쪽/아래쪽으로만 이동
    - 웅덩이는 지나갈 수 없음
    - 가능한 최단 경로의 개수를 구하기

    [접근 과정]
    1. 처음에는 모든 경로를 탐색하는 DFS/백트래킹을 생각할 수 있다.
       - 현재 위치에서 오른쪽/아래쪽으로 이동하며 모든 경우를 탐색

    2. 하지만 여러 경로가 동일한 위치에 도착할 수 있다.
       - DFS로 탐색하면 같은 위치 이후의 경로를 반복해서 계산하게 됨.
       - m, n <= 100이므로 모든 경로를 직접 탐색하는 것은 비효율적이다.

    3. 현재 위치까지 오는 경로의 수는 이전 위치들의 결과만 알면 계산할 수 있다.
       - (x, y)로 올 수 있는 방법:
         ① 위쪽 (x, y-1)에서 내려오기
         ② 왼쪽 (x-1, y)에서 오른쪽으로 오기

    4. 따라서 DP 사용
       - dp[y][x] = (x, y)까지 도달할 수 있는 경로의 수
       - dp[y][x] = dp[y-1][x] + dp[y][x-1]
       - 웅덩이인 경우 dp[y][x] = 0

    [DP를 떠올리는 포인트]
    - DFS로 풀었을 때 같은 상태를 여러 번 계산하는가?
    - 현재 상태의 답을 이전 상태의 답으로 만들 수 있는가?
    → 그렇다면 DP를 고려해볼 수 있다.

    시간복잡도: O(n * m)
    공간복잡도: O(n * m)
    '''

    MOD = 1_000_000_007

    dp = [[0] * m for _ in range(n)]
    puddles = {(x - 1, y - 1) for x, y in puddles}

    # 시작점까지 오는 경로는 1개
    dp[0][0] = 1

    for y in range(n):
        for x in range(m):
            # 웅덩이는 도달할 수 없으므로 경로의 수가 0
            if (x, y) in puddles:
                dp[y][x] = 0
                continue

            if x == 0 and y == 0:
                continue

            # 위에서 현재 위치로 오는 경우
            if y > 0:
                dp[y][x] += dp[y - 1][x]

            # 왼쪽에서 현재 위치로 오는 경우
            if x > 0:
                dp[y][x] += dp[y][x - 1]

            dp[y][x] %= MOD

    return dp[n - 1][m - 1]